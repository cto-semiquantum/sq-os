uint8_t *draw_buffer = (uint8_t *)BACKBUFFER_ADDR;

/* clear_backbuffer — zero the entire 320x200 backbuffer (16000 dwords) */
void clear_backbuffer(void) {
    uint32_t *buf = (uint32_t *)BACKBUFFER_ADDR;
    for (int i = 0; i < 16000; i++) {
        buf[i] = 0;
    }
}

