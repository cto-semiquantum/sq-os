void draw_pixel(int x, int y, uint8_t color) {
    if (x >= 0 && x < VGA_WIDTH && y >= 0 && y < VGA_HEIGHT) {
        draw_buffer[y * VGA_WIDTH + x] = color;
    }
}

void draw_rect(int x, int y, int width, int height, uint8_t color) {
    // Clipping
    if (x < 0) {
        width += x;
        x = 0;
    }
    if (y < 0) {
        height += y;
        y = 0;
    }
    if (x + width > VGA_WIDTH) {
        width = VGA_WIDTH - x;
    }
    if (y + height > VGA_HEIGHT) {
        height = VGA_HEIGHT - y;
    }
    if (width <= 0 || height <= 0) return;

    for (int r = 0; r < height; r++) {
        uint8_t *dest = &draw_buffer[(y + r) * VGA_WIDTH + x];
        for (int c = 0; c < width; c++) {
            dest[c] = color;
        }
    }
}

void draw_char(int x, int y, char c, uint8_t color) {
    // Map lowercase to uppercase
    if (c >= 'a' && c <= 'z') {
        c -= 32;
    }

    if (c < 32 || c > 90) return;

    int glyph_idx = c - 32;
    const uint8_t *glyph = &font8x8[glyph_idx * 8];

    for (int r = 0; r < 8; r++) {
        int cy = y + r;
        if (cy < 0 || cy >= VGA_HEIGHT) continue;

        uint8_t row_data = glyph[r];
        uint8_t *dest = &draw_buffer[cy * VGA_WIDTH];

        for (int col = 0; col < 8; col++) {
            int cx = x + col;
            if (cx < 0 || cx >= VGA_WIDTH) continue;

            if (row_data & (0x80 >> col)) {
                dest[cx] = color;
            }
        }
    }
}

void draw_text(int x, int y, const char *str, uint8_t color) {
    while (*str) {
        draw_char(x, y, *str, color);
        x += 8;
        str++;
    }
}

void draw_char_clipped(int x, int y, char c, uint8_t color, int min_x, int max_x, int min_y, int max_y) {
    if (c >= 'a' && c <= 'z') {
        c -= 32;
    }
    if (c < 32 || c > 90) return;

    int glyph_idx = c - 32;
    const uint8_t *glyph = &font8x8[glyph_idx * 8];

    for (int r = 0; r < 8; r++) {
        int cy = y + r;
        if (cy < min_y || cy >= max_y || cy < 0 || cy >= VGA_HEIGHT) continue;

        uint8_t row_data = glyph[r];
        uint8_t *dest = &draw_buffer[cy * VGA_WIDTH];

        for (int col = 0; col < 8; col++) {
            int cx = x + col;
            if (cx < min_x || cx >= max_x || cx < 0 || cx >= VGA_WIDTH) continue;

            if (row_data & (0x80 >> col)) {
                dest[cx] = color;
            }
        }
    }
}

void draw_text_clipped(int x, int y, const char *str, uint8_t color, int min_x, int max_x, int min_y, int max_y) {
    while (*str) {
        if (x >= max_x) break;
        if (x + 8 > min_x) {
            draw_char_clipped(x, y, *str, color, min_x, max_x, min_y, max_y);
        }
        x += 8;
        str++;
    }
}

void swap_buffers(void) {
    // Wait for vertical retrace (Vsync)
    // First wait for any ongoing retrace to end
    while (inb(0x3DA) & 0x08);
    // Then wait for a new retrace to start
    while (!(inb(0x3DA) & 0x08));

    // Copy backbuffer (0x50000) to VGA framebuffer (0xA0000)
    // 320 * 200 = 64000 bytes. 16000 dwords.
    uint32_t *src = (uint32_t *)BACKBUFFER_ADDR;
    uint32_t *dest = (uint32_t *)VGA_FRAMEBUFFER_ADDR;
    for (int i = 0; i < 16000; i++) {
        dest[i] = src[i];
    }
}
