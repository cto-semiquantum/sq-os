# Font functions to insert before dispatch_done
font_funcs = '''
; ==========================================
; BITMAP FONT RENDERER (8x8 pixels/char)
; ==========================================

; draw_char: EBX=x, ECX=y, AL=char, AH=color
draw_char:
    pushad
    movzx ebp, ah          ; save color in EBP
    movzx esi, al
    sub esi, 32
    jl .dc_exit
    shl esi, 3
    add esi, font8x8
    xor edx, edx           ; row counter
.dc_row:
    cmp edx, 8
    jge .dc_exit
    movzx eax, byte [esi + edx]   ; glyph row byte
    xor edi, edi           ; col counter
.dc_col:
    cmp edi, 8
    jge .dc_next_row
    test al, 0x80
    jz .dc_skip
    ; compute pixel address
    push eax
    push edi
    mov eax, ecx
    add eax, edx           ; y = base_y + row
    imul eax, eax, 320
    add eax, ebx           ; + base_x
    pop edi
    add eax, edi           ; + col
    add eax, 0xA0000
    mov byte [eax], bpl    ; write color
    push edi
    pop edi
    pop eax
.dc_skip:
    shl al, 1              ; next bit
    inc edi
    jmp .dc_col
.dc_next_row:
    inc edx
    jmp .dc_row
.dc_exit:
    popad
    ret

; draw_text: ESI=str, EBX=x, ECX=y, DL=color
draw_text:
    pushad
.dt_loop:
    mov al, [esi]
    or al, al
    jz .dt_done
    mov ah, dl
    call draw_char
    add ebx, 8
    inc esi
    jmp .dt_loop
.dt_done:
    popad
    ret

'''

content = content.replace('dispatch_done:', font_funcs + '\ndispatch_done:')

