; =============================================
; gui/graphics.asm
; Primitive drawing routines: rect, window, char, text
; Font data (8x8 bitmap, ASCII 32-90)
; =============================================

VGA_FRAMEBUFFER equ 0xA0000
BACKBUFFER      equ 0x50000

; ---- draw_rect_pm ----
; EBX=x, ECX=y, EDX=width, ESI=height, AL=color
; Clips to 320x200, writes to [draw_buffer]
draw_rect_pm:
    pushad

    ; Save color in AH
    mov ah, al

    ; Clip Y:
    cmp ecx, 0
    jge .clip_y_top_ok
    add esi, ecx
    xor ecx, ecx
    cmp esi, 0
    jle .done
.clip_y_top_ok:
    cmp ecx, 200
    jge .done
    mov edi, ecx
    add edi, esi
    cmp edi, 200
    jle .clip_y_bottom_ok
    mov esi, 200
    sub esi, ecx
    cmp esi, 0
    jle .done
.clip_y_bottom_ok:

    ; Clip X:
    cmp ebx, 0
    jge .clip_x_left_ok
    add edx, ebx
    xor ebx, ebx
    cmp edx, 0
    jle .done
.clip_x_left_ok:
    cmp ebx, 320
    jge .done
    mov edi, ebx
    add edi, edx
    cmp edi, 320
    jle .clip_x_right_ok
    mov edx, 320
    sub edx, ebx
    cmp edx, 0
    jle .done
.clip_x_right_ok:

    ; Compute initial address in EDI
    mov eax, ecx
    imul eax, eax, 320
    add eax, ebx
    add eax, [draw_buffer]
    mov edi, eax

    mov ebp, esi            ; EBP = row loop counter (height)
    mov al, ah              ; AL = color for stosb
    cld

.row_loop:
    push edi
    mov ecx, edx            ; ECX = width
    rep stosb
    pop edi
    add edi, 320
    dec ebp
    jnz .row_loop

.done:
    popad
    ret


; ---- draw_char ----
; EBX=x, ECX=y, AL=char, AH=color
; Draws an 8x8 character using the font8x8 bitmap, writes to [draw_buffer]
draw_char:
    pushad

    ; Map lowercase to uppercase
    cmp al, 'a'
    jl .not_lower
    cmp al, 'z'
    jg .not_lower
    sub al, 32
.not_lower:

    ; Printable range check (32 to 90)
    cmp al, 32
    jl .done
    cmp al, 90
    jg .done

    ; Get offset of glyph: (char - 32) * 8
    sub al, 32
    movzx esi, al
    shl esi, 3
    add esi, font8x8

    ; Save color in DH
    mov dh, ah

    xor ebp, ebp            ; EBP = row counter (0..7)

.row_loop:
    cmp ebp, 8
    jge .done

    ; Check Y bounds: y + row
    mov edi, ecx
    add edi, ebp
    cmp edi, 0
    jl .next_row
    cmp edi, 200
    jge .next_row

    ; Calculate screen row base address
    imul edi, edi, 320
    add edi, [draw_buffer]

    ; Load glyph row byte
    movzx eax, byte [esi + ebp]

    push ebx                ; Save base x
    xor ecx, ecx            ; ECX = col counter (0..7)

.col_loop:
    cmp ecx, 8
    jge .col_done

    mov ebx, [esp]          ; EBX = base x
    add ebx, ecx
    cmp ebx, 0
    jl .pixel_skip
    cmp ebx, 320
    jge .pixel_skip

    test al, 0x80
    jz .pixel_skip

    mov [edi + ebx], dh     ; Write pixel color

.pixel_skip:
    shl al, 1
    inc ecx
    jmp .col_loop

.col_done:
    pop ebx                 ; Restore base x
    mov ecx, [esp + 24]     ; Restore original ECX (y) which was overwritten in col_loop!
                            ; Wait, pushad saves: EAX, ECX, EDX, EBX, ESP, EBP, ESI, EDI.
                            ; [esp + 24] is ECX in the pushad frame!
                            ; Let's check: pushad push order is:
                            ;   ESP + 28: EAX
                            ;   ESP + 24: ECX
                            ;   ESP + 20: EDX
                            ;   ESP + 16: EBX
                            ;   ESP + 12: ESP
                            ;   ESP +  8: EBP
                            ;   ESP +  4: ESI
                            ;   ESP +  0: EDI
                            ; Since we just popped EBX, ESP is back to its value before the push ebx,
                            ; so ECX is indeed at [esp + 24].
                            ; Let's verify this restore.

.next_row:
    inc ebp
    jmp .row_loop

.done:
    popad
    ret

; ---- draw_text ----
; ESI=str, EBX=x, ECX=y, DL=color
draw_text:
    pushad
.dt_loop:
    mov al, [esi]
    or al, al
    jz .dt_done
    mov ah, dl
    call draw_char
    add ebx, 8
    inc esi
    jmp .dt_loop
.dt_done:
    popad
    ret

; =============================================
; GRAPHICS DATA
; =============================================
draw_buffer     dd BACKBUFFER   ; target render buffer (defaults to backbuffer)


