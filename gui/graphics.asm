; =============================================
; gui/graphics.asm
; Primitive drawing routines: rect, window, char, text
; Font data (8x8 bitmap, ASCII 32-90)
; =============================================

; ---- draw_rect_pm ----
; EBX=x, ECX=y, EDX=width, ESI=height, AL=color
; Clips to 320x200, writes to [draw_buffer]
draw_rect_pm:
    pushad
    mov [rect_x], ebx
    mov [rect_y], ecx
    mov [rect_w], edx
    mov [rect_h], esi
    mov [rect_c], al

    mov dword [rect_row], 0
.rect_row_loop:
    mov eax, [rect_row]
    cmp eax, [rect_h]
    jae .rect_done

    ; y = rect_y + rect_row
    mov eax, [rect_y]
    add eax, [rect_row]

    ; Clip Y: 0 <= y < 200
    cmp eax, 0
    jl .rp_next_row
    cmp eax, 200
    jge .rp_next_row

    ; Load x and width, clip X
    mov ebx, [rect_x]
    mov edx, [rect_w]

    ; Clip left
    cmp ebx, 0
    jge .rp_clip_right
    add edx, ebx
    xor ebx, ebx
    cmp edx, 0
    jle .rp_next_row

.rp_clip_right:
    mov edi, ebx
    add edi, edx
    cmp edi, 320
    jle .rp_draw
    mov edx, 320
    sub edx, ebx
    cmp edx, 0
    jle .rp_next_row

.rp_draw:
    imul eax, eax, 320
    add eax, ebx
    add eax, [draw_buffer]
    mov edi, eax
    mov ecx, edx
    mov al, [rect_c]
    cld
    rep stosb

.rp_next_row:
    inc dword [rect_row]
    jmp .rect_row_loop
.rect_done:
    popad
    ret

; ---- draw_window_pm ----
; EBX=x, ECX=y, EDX=width, ESI=height, EDI=title_str
; Draws Win95-style 3D bevelled window with title bar + close button
draw_window_pm:
    pushad
    mov [win_x_var], ebx
    mov [win_y_var], ecx
    mov [win_w_var], edx
    mov [win_h_var], esi
    mov [win_title_ptr], edi

    ; 1. Body (light gray = 7)
    mov al, 7
    call draw_rect_pm

    ; 2. Top highlight (white = 15)
    mov ebx, [win_x_var]
    mov ecx, [win_y_var]
    mov edx, [win_w_var]
    mov esi, 1
    mov al, 15
    call draw_rect_pm
    ; Left highlight
    mov ebx, [win_x_var]
    mov ecx, [win_y_var]
    mov edx, 1
    mov esi, [win_h_var]
    mov al, 15
    call draw_rect_pm

    ; 3. Bottom shadow (dark gray = 8)
    mov ebx, [win_x_var]
    mov ecx, [win_y_var]
    add ecx, [win_h_var]
    dec ecx
    mov edx, [win_w_var]
    mov esi, 1
    mov al, 8
    call draw_rect_pm
    ; Right shadow
    mov ebx, [win_x_var]
    add ebx, [win_w_var]
    dec ebx
    mov ecx, [win_y_var]
    mov edx, 1
    mov esi, [win_h_var]
    mov al, 8
    call draw_rect_pm

    ; 4. Title bar (blue = 1)
    mov ebx, [win_x_var]
    add ebx, 2
    mov ecx, [win_y_var]
    add ecx, 2
    mov edx, [win_w_var]
    sub edx, 4
    mov esi, 10
    mov al, 1
    call draw_rect_pm

    ; 5. Title text (white = 15)
    mov esi, [win_title_ptr]
    mov ebx, [win_x_var]
    add ebx, 6
    mov ecx, [win_y_var]
    add ecx, 3
    mov dl, 15
    call draw_text

    ; 6. Close button (red = 12)
    mov ebx, [win_x_var]
    add ebx, [win_w_var]
    sub ebx, 11
    mov ecx, [win_y_var]
    add ecx, 3
    mov edx, 6
    mov esi, 6
    mov al, 12
    call draw_rect_pm

    popad
    ret

; ---- draw_char ----
; EBX=x, ECX=y, AL=char, AH=color
; Clips each pixel to 320x200, writes to [draw_buffer]
draw_char:
    mov [dc_char],  al
    mov [dc_color], ah
    mov [dc_basex], ebx
    mov [dc_basey], ecx
    pushad
    movzx eax, byte [dc_char]
    sub eax, 32
    jl .dc_exit
    shl eax, 3
    add eax, font8x8
    mov [dc_glyph], eax

    mov dword [dc_row], 0
.dc_row:
    cmp dword [dc_row], 8
    jge .dc_exit

    mov esi, [dc_glyph]
    mov ecx, [dc_row]
    movzx eax, byte [esi + ecx]
    mov [dc_bits], al

    mov dword [dc_col], 0
.dc_col:
    cmp dword [dc_col], 8
    jge .dc_next_row

    mov al, [dc_bits]
    test al, 0x80
    jz .dc_skip

    ; Clip Y
    mov eax, [dc_basey]
    add eax, [dc_row]
    cmp eax, 0
    jl .dc_skip
    cmp eax, 200
    jge .dc_skip

    ; Clip X
    mov ebx, [dc_basex]
    add ebx, [dc_col]
    cmp ebx, 0
    jl .dc_skip
    cmp ebx, 320
    jge .dc_skip

    ; Write pixel to draw_buffer
    imul eax, eax, 320
    add eax, ebx
    add eax, [draw_buffer]
    movzx ebx, byte [dc_color]
    mov [eax], bl

.dc_skip:
    mov al, [dc_bits]
    shl al, 1
    mov [dc_bits], al
    inc dword [dc_col]
    jmp .dc_col

.dc_next_row:
    inc dword [dc_row]
    jmp .dc_row

.dc_exit:
    popad
    ret

; ---- draw_text ----
; ESI=str, EBX=x, ECX=y, DL=color
draw_text:
    pushad
.dt_loop:
    mov al, [esi]
    or al, al
    jz .dt_done
    mov ah, dl
    call draw_char
    add ebx, 8
    inc esi
    jmp .dt_loop
.dt_done:
    popad
    ret

; =============================================
; GRAPHICS DATA
; =============================================
draw_buffer     dd 0xA0000      ; target render buffer (front or back)

rect_x          dd 0
rect_y          dd 0
rect_w          dd 0
rect_h          dd 0
rect_c          db 0
rect_row        dd 0

win_x_var       dd 0
win_y_var       dd 0
win_w_var       dd 0
win_h_var       dd 0
win_title_ptr   dd 0

